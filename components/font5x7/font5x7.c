/**
 * @brief Stand-in for a character the font does not cover.
 *
 * A solid block, so an unexpected byte is unmistakable on the panel instead of
 * looking like a space someone meant to put there.
 */
static const uint8_t MISSING[FONT5X7_WIDTH] = { 0x7F, 0x7F, 0x7F, 0x7F, 0x7F };

const uint8_t *font5x7_glyph(char c)
{
    /* Through unsigned char, because `char` is signed on this target and a byte
     * above 0x7F would otherwise compare as negative and index backwards out of the
     * table — a sign-extension bug that only shows up on input nobody tested with. */
    const unsigned char code = (unsigned char)c;

    if (code < FIRST_CHAR || code > LAST_CHAR) {
        return MISSING;
    }

    return GLYPHS[code - FIRST_CHAR];
}
